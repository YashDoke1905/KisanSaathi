// Haversine formula for real distance in km
export function calculateMandiDistance(farmerDistrict: string, mandiLat: number, mandiLng: number): number {
  const coords = DISTRICT_COORDINATES[farmerDistrict] || DISTRICT_COORDINATES.Nashik;
  const R = 6371; // Earth radius in km
  const dLat = ((mandiLat - coords.lat) * Math.PI) / 180;
  const dLng = ((mandiLng - coords.lng) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((coords.lat * Math.PI) / 180) *
      Math.cos((mandiLat * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.max(12, Math.round(R * c)); // minimum 12 km to local mandi yard
}

